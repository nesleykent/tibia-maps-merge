export function t(key, ...args) {
  const entry = STRINGS[key];
  return typeof entry === 'function' ? entry(...args) : entry;
}

/** Display name for a marker icon; falls back to its canonical format name. */
export function iconLabel(name) {
  return ICON_LABELS[name] ?? name;
}

export function localeNumber(n) {
  return n.toLocaleString('en-US');
}

export function localeDate(date) {
  if (!date) return t('unknownDate');
  return date.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
}
